"""Exhaustive (exact) enumeration of all integer vectors h with ||h||_inf <= H and |h.v| <= H^-2, v = (1, alpha, beta),
alpha = sqrt(log2/log3), beta = sqrt(log2/log5), at the scales H = 2^k, k = KMIN..KMAX.

Method: rank-3 lattice in Z^4 generated by (e_i, round(W v_i)), W = H^3.  If ||h||_inf <= H and |h.v| <= H^-2 then the lattice vector
(h, round-sum) has |h_i| <= H and last coordinate <= W H^-2 + 1.5 H <= 2.5 H, so squared norm <= 3 H^2 + 6.25 H^2 < 10 H^2.  After LLL reduction all
lattice vectors of norm^2 <= 10 H^2 are enumerated exactly (Fincke-Pohst, rational arithmetic) and filtered by the true condition (|h.v| in 400-digit arithmetic).
Every h with 1 <= ||h|| <= 2^KMAX and  |h.v| ||h||^2 <= 1/4  has H = 2^ceil(log2 ||h||) <= 2 ||h|| and |h.v| <= H^-2 and is therefore found.
So the minimum of |h.v| ||h||^2 over ALL nonzero h with ||h|| <= 2^KMAX is  >= min(1/4, min over the listed vectors).
Usage: exhaustive_hv.py KMIN KMAX"""
import sys, math, time
from fractions import Fraction
from decimal import Decimal, getcontext
KMIN, KMAX = int(sys.argv[1]), int(sys.argv[2])
getcontext().prec = int(3.2 * KMAX * 0.30103 * 2) + 120
L2, L3, L5 = Decimal(2).ln(), Decimal(3).ln(), Decimal(5).ln()
alpha, beta = (L2 / L3).sqrt(), (L2 / L5).sqrt()
v = [Decimal(1), alpha, beta]

def dot(a, b): return sum(x * y for x, y in zip(a, b))
def lll(B, delta=Fraction(99, 100)):
    n = len(B); B = [list(r) for r in B]
    def gs():
        Bs, mu = [], [[Fraction(0)] * n for _ in range(n)]
        for i in range(n):
            w = [Fraction(x) for x in B[i]]
            for j in range(i):
                mu[i][j] = dot(B[i], Bs[j]) / dot(Bs[j], Bs[j])
                w = [a - mu[i][j] * b for a, b in zip(w, Bs[j])]
            Bs.append(w)
        return Bs, mu
    Bs, mu = gs(); k = 1
    while k < n:
        for j in range(k - 1, -1, -1):
            q = round(mu[k][j])
            if q:
                B[k] = [a - q * b for a, b in zip(B[k], B[j])]; Bs, mu = gs()
        if dot(Bs[k], Bs[k]) >= (delta - mu[k][k - 1] ** 2) * dot(Bs[k - 1], Bs[k - 1]): k += 1
        else:
            B[k], B[k - 1] = B[k - 1], B[k]; Bs, mu = gs(); k = max(k - 1, 1)
    return B, Bs, mu

def enumerate_short(B, Bs, mu, R2, limit=2000000):
    n = len(B); nb = [dot(Bs[i], Bs[i]) for i in range(n)]; out = []
    def rec(i, ks, rest):
        if len(out) > limit: return
        if i < 0:
            out.append(list(ks)); return
        c = -sum(ks[j] * mu[j][i] for j in range(i + 1, n)) if i < n - 1 else Fraction(0)
        rad2 = rest / nb[i]
        r = math.isqrt(int(rad2)) + 1 if rad2 > 0 else 0
        for k in range(math.floor(c - r - 1), math.ceil(c + r + 1) + 1):
            t = (k - c) ** 2 * nb[i]
            if t <= rest:
                ks[i] = k; rec(i - 1, ks, rest - t)
        ks[i] = 0
    rec(n - 1, [0] * n, R2)
    return out

found = {}
t0 = time.time()
for k in range(KMIN, KMAX + 1):
    H = 2 ** k
    W = H ** 3
    basis = [[1, 0, 0, int(round(Decimal(W) * v[0]))], [0, 1, 0, int(round(Decimal(W) * v[1]))], [0, 0, 1, int(round(Decimal(W) * v[2]))]]
    B, Bs, mu = lll(basis)
    vecs = enumerate_short(B, Bs, mu, Fraction(10 * H * H))
    cnt = 0
    for ks in vecs:
        h = [sum(ks[i] * B[i][j] for i in range(3)) for j in range(3)]
        if h == [0, 0, 0]: continue
        hinf = max(abs(x) for x in h)
        if hinf > H: continue
        hv = abs(Decimal(h[0]) + Decimal(h[1]) * alpha + Decimal(h[2]) * beta)
        if hv * H * H <= 1:
            # normalize sign and store
            key = tuple(h) if tuple(h) > tuple(-x for x in h) else tuple(-x for x in h)
            if key not in found:
                found[key] = (hinf, hv); cnt += 1
    print("k=%2d H=2^%d  lattice vectors enumerated: %7d   new exceptional h: %d   [%.0fs]" % (k, k, len(vecs), cnt, time.time() - t0)); sys.stdout.flush()
rows = sorted(found.items(), key=lambda kv: kv[1][0])
print("\nexceptional vectors (|h.v| <= H^-2 at their scale), sorted by norm:  ||h||_inf, |h.v|, |h.v| ||h||^2, J = -log|h.v|/log||h||, h")
minprod = Decimal(1); maxJ = 0.0
for h, (hinf, hv) in rows:
    prod = hv * hinf * hinf
    J = float(-hv.ln() / Decimal(hinf).ln()) if hinf > 1 else float('nan')
    minprod = min(minprod, prod)
    if hinf >= 30: maxJ = max(maxJ, J)
    print("%d  %.3e  %.4f  %.3f  %s" % (hinf, float(hv), float(prod), J, list(h)))
print("\nmin |h.v| ||h||^2 over the listed vectors: %.4f ; max exponent J over listed vectors with ||h|| >= 30: %.3f" % (float(minprod), maxJ))
