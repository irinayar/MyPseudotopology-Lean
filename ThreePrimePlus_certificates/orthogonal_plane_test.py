"""Elementary transference: for z = (n,m,l) in Z^3 let h be a shortest nonzero integer vector orthogonal to z (the lattice z^perp ∩ Z^3 has rank 2
and covolume |z|_2 / gcd(n,m,l) <= |z|_2, so |h|_2 <= (2/sqrt(3))^(1/2) sqrt(|z|_2)).  Then h.z = 0, z = n v + e with e = (0, u, w),
u = m - alpha n, w = l - beta n, hence h.v = -(h1 u + h2 w)/n.   This script computes h for the known close triples by exact LLL on
the lattice generated by the rows (e_i, K z_i) and checks  |h|_inf <= 2 sqrt(n),  |h.v| <= 2 delta / sqrt(n)  (delta = max(|u|,|w|)),
and prints the exponent  J(h) = -log|h.v| / log|h|_inf  of the vector found."""
import math, sys
from fractions import Fraction
from decimal import Decimal, getcontext
getcontext().prec = 80
L2, L3, L5 = Decimal(2).ln(), Decimal(3).ln(), Decimal(5).ln()
alpha, beta = (L2 / L3).sqrt(), (L2 / L5).sqrt()

def dot(a, b): return sum(x * y for x, y in zip(a, b))
def lll(B, delta=Fraction(99, 100)):
    n = len(B); B = [list(r) for r in B]
    def gs():
        Bs, mu = [], [[Fraction(0)] * n for _ in range(n)]
        for i in range(n):
            w = [Fraction(x) for x in B[i]]
            for j in range(i):
                mu[i][j] = dot(B[i], Bs[j]) / dot(Bs[j], Bs[j])
                w = [a - mu[i][j] * b for a, b in zip(w, Bs[j])]
            Bs.append(w)
        return Bs, mu
    Bs, mu = gs(); k = 1
    while k < n:
        for j in range(k - 1, -1, -1):
            q = round(mu[k][j])
            if q:
                B[k] = [a - q * b for a, b in zip(B[k], B[j])]; Bs, mu = gs()
        if dot(Bs[k], Bs[k]) >= (delta - mu[k][k - 1] ** 2) * dot(Bs[k - 1], Bs[k - 1]): k += 1
        else:
            B[k], B[k - 1] = B[k - 1], B[k]; Bs, mu = gs(); k = max(k - 1, 1)
    return B

triples = [(32,25,21),(35,28,23),(58,46,38),(64,51,42),(102,81,67),(224,178,147),(413,328,271),(739,587,485),(1123,892,737),(2144,1703,1407),(3267,2595,2144),(5766,4580,3784),(39268,31191,25770)]
print("      n   |h|_inf  2sqrt(n)    |h.v|        2 delta/sqrt(n)   J(h)")
for (n, m, l) in triples:
    K = 10 ** 12 * n
    B = lll([[1, 0, 0, K * n], [0, 1, 0, K * m], [0, 0, 1, K * l]])
    cand = [r for r in B if r[3] == 0]
    cand.sort(key=lambda r: dot(r, r))
    h = cand[0][:3]
    hv = abs(Decimal(h[0]) + Decimal(h[1]) * alpha + Decimal(h[2]) * beta)
    u, w = abs(m - alpha * n), abs(l - beta * n)
    delta = max(u, w)
    hinf = max(abs(x) for x in h)
    bound = 2 * delta / Decimal(n).sqrt()
    J = float(-hv.ln() / Decimal(hinf).ln()) if hinf > 1 else float('nan')
    ok = (hinf <= 2 * math.sqrt(n)) and (hv <= bound)
    print("%7d  %6d  %8.1f   %.3e   %.3e      %.2f  %s  h=%s" % (n, hinf, 2 * math.sqrt(n), float(hv), float(bound), J, "ok" if ok else "VIOLATION", h))
